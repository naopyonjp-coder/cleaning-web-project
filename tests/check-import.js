assert.equal(run("buildImport(getDraft('1'),'1').rooms[0].towel"),6);
run("getDraft('1').rooms[0].overrides={}");
run("getDraft('1').date='2099-02-30'");
assert.throws(()=>run("buildImport(getDraft('1'),'1')"));
