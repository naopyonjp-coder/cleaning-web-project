assert(!review.includes('<img src=https://example.invalid/secret'),'custom notes escaped');
run('applyImport()');
assert.equal(run('JSON.stringify(DATA)'),initial,'human confirmation required');
document.getElementById('import-agree').checked=true;
run('applyImport()');
assert.equal(run("DATA['1'].source"),'local');
